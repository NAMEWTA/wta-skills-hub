#!/usr/bin/env node
// Maintainer-only build. Explicit --fetch authorizes npm registry access.
// Never invoked by the installer, skill, status line, test suite, or prepack.
import { mkdtemp, mkdir, readdir, readFile, writeFile, copyFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'skills/system/optimize-codex-config/scripts/vendor');
if (process.argv.slice(2).join(' ') !== '--fetch') {
  console.error('Usage: node scripts/build-ai-cli-config-vendor.mjs --fetch (maintainer network operation)');
  process.exit(2);
}
const packages = {
  'toml-eslint-parser': '1.0.3',
  'eslint-visitor-keys': '5.0.0',
  'jsonc-parser': '3.3.1',
  'esbuild': '0.25.5',
};
const work = await mkdtemp(join(tmpdir(), 'wta-parser-build-'));
try {
  await writeFile(join(work, 'package.json'), JSON.stringify({ private: true, type: 'module', dependencies: packages }));
  let locked = false;
  try { await copyFile(join(target, 'build-package-lock.json'), join(work, 'package-lock.json')); locked = true; }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
  const installed = spawnSync(npm, [locked ? 'ci' : 'install', '--ignore-scripts', '--no-audit', '--no-fund'], {
    cwd: work, stdio: 'inherit', shell: process.platform === 'win32', timeout: 180000,
  });
  if (installed.status !== 0) throw new Error('Pinned parser dependency installation failed');
  const entry = join(work, 'entry.mjs');
  await writeFile(entry, [
    "export { parseTOML, getStaticTOMLValue } from 'toml-eslint-parser';",
    "export { parseTree, getNodeValue, findNodeAtLocation, modify, applyEdits } from 'jsonc-parser/lib/esm/main.js';",
    '',
  ].join('\n'));
  const require = createRequire(join(work, 'package.json'));
  const { build } = require('esbuild');
  await mkdir(target, { recursive: true });
  await build({ entryPoints: [entry], outfile: join(target, 'parsers.mjs'), bundle: true,
    platform: 'node', target: 'node22', format: 'esm', minify: true, legalComments: 'inline',
    banner: { js: '// Generated by scripts/build-ai-cli-config-vendor.mjs. See THIRD-PARTY-NOTICES.txt.' },
  });
  const parser = await import(pathToFileURL(join(target, 'parsers.mjs')).href);
  if (parser.getStaticTOMLValue(parser.parseTOML('answer = 42')).answer !== 42 || !parser.parseTree('{}')) {
    throw new Error('Standalone parser smoke failed');
  }
  const notices = [];
  for (const name of ['toml-eslint-parser', 'eslint-visitor-keys', 'jsonc-parser']) {
    const directory = join(work, 'node_modules', name);
    const filename = (await readdir(directory)).find(item => /^license(?:\.|$)/i.test(item));
    if (!filename) throw new Error('Required upstream license missing: ' + name);
    notices.push(name + '@' + packages[name] + '\n' + await readFile(join(directory, filename), 'utf8'));
  }
  await writeFile(join(target, 'THIRD-PARTY-NOTICES.txt'), notices.join('\n\n'));
  await copyFile(join(work, 'package-lock.json'), join(target, 'build-package-lock.json'));
  const bytes = await readFile(join(target, 'parsers.mjs'));
  await writeFile(join(target, 'manifest.json'), JSON.stringify({ schema_version: 1, packages,
    sha256: createHash('sha256').update(bytes).digest('hex'),
    runtime_network: false, runtime_dependencies: [],
    toml_version: '1.0.0', json_policy: 'strict; comments and duplicate keys rejected',
  }, null, 2) + '\n');
  console.log('Parser bundle generated: ' + bytes.length + ' bytes');
} finally {
  await rm(work, { recursive: true, force: true });
}
